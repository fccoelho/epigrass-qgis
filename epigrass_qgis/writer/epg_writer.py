"""Writers for the Epigrass model project (model.epg, sites.csv, edges.csv).

This module is pure Python (no QGIS imports) so it can be unit tested anywhere.

The formats match what ``Epigrass.manager.Simulate`` expects when parsing a
project (see ``loadModelScript``/``instSites``/``instEdges`` in the Epigrass
source):

* ``sites.csv``  -> positional columns: lat, long, name, population, geocode, [values...]
* ``edges.csv``  -> positional columns: Source, Dest, flowSD, flowDS, Distance, geoSource, geoDest
* ``model.epg``  -> INI-like script with the seven well known sections.  Values are
  parsed with ``ConfigParser`` (keys lowercased) and ``eval``-ed where needed, so
  lists/tuples must be rendered as valid Python literals.
"""

from __future__ import annotations

import csv
import json
import logging
import re
from dataclasses import dataclass, field
from pathlib import Path

log = logging.getLogger(__name__)

SITES_HEADER = ["lat", "long", "City", "Pop", "Geocode"]
EDGES_HEADER = ["Source", "Dest", "flowSD", "flowDS", "Distance", "geoSource", "geoDest"]

#: characters kept when deriving file/table-safe model names from layer names
_MODEL_NAME_BAD = re.compile(r"[^A-Za-z0-9_\-]+")


def sanitize_model_name(name: str) -> str:
    """Reduce *name* to something safe for file names, SQLite tables and .epg.

    The model name flows into the output directory name (``outdata-<name>``)
    and the SQLite result table name, so anything outside ASCII letters,
    digits, underscore and dash is replaced.
    """
    cleaned = _MODEL_NAME_BAD.sub("_", (name or "").strip())
    return cleaned.strip("_-") or "model"

_EPG_TEMPLATE = """################################################################
#  EPIGRASS - Model definition                                 #
#  Generated by the Epigrass plugin for QGIS.                  #
#  It can be edited by hand with a text editor.                #
################################################################

#==============================================================#
[THE WORLD]
#==============================================================#
# Background map layer: [file, name field, geocode field]
shapefile = {shapefile}
sites = sites.csv
edges = edges.csv
encoding = {encoding}

#==============================================================#
[EPIDEMIOLOGICAL MODEL]
#==============================================================#
modtype = {modtype}

#==============================================================#
[MODEL PARAMETERS]
#==============================================================#
# Parameters may be constants or expressions of N (site population)
# and of values[i] (extra columns of the sites file).
beta = {beta}
alpha = {alpha}
e = {e}
r = {r}
delta = {delta}
B = {B}
w = {w}
p = {p}

#==============================================================#
[INITIAL CONDITIONS]
#==============================================================#
{inits}

#==============================================================#
[EPIDEMIC EVENTS]
#==============================================================#
seed = {seed}
Vaccinate = {vaccinate}
Quarantine = {quarantine}

#==============================================================#
[TRANSPORTATION MODEL]
#==============================================================#
doTransp = {do_transp}
stochastic = {stochastic}
speed = {speed}

#==============================================================#
[SIMULATION AND OUTPUT]
#==============================================================#
steps = {steps}
outdir =
sqlout = {sqlout}
report = {report}
siteRep = {site_rep}
Replicas = {replicas}
RandSeed = {rand_seed}
Batch = {batch}
"""


@dataclass
class Site:
    """One metapopulation site (city, zone, region...)."""

    name: str
    population: float
    geocode: int
    lat: float
    lon: float
    values: tuple = ()  # extra columns, referenced in .epg as values[0], values[1]...

    def __post_init__(self) -> None:
        self.population = float(self.population)
        self.geocode = int(self.geocode)
        self.lat = float(self.lat)
        self.lon = float(self.lon)


@dataclass
class Edge:
    """A directional pair of flows between two sites (one row of edges.csv)."""

    source: int  # geocode of the source site
    dest: int  # geocode of the destination site
    flow_sd: float = 0.0  # flow source -> dest
    flow_ds: float = 0.0  # flow dest -> source
    distance_km: float = 0.0

    def __post_init__(self) -> None:
        self.source = int(self.source)
        self.dest = int(self.dest)


@dataclass
class SeedEvent:
    """Initial infected individuals added to a site at t=0."""

    geocode: int
    state: str = "I"  # must be one of the initial-condition keys (S, E, I)
    amount: int = 1


@dataclass
class VaccinationEvent:
    """Vaccination campaign: coverage fractions applied at given time steps.

    ``geocode`` may be the string ``"all"`` to target every site.
    """

    geocode: object  # int geocode or "all"
    times: list = field(default_factory=list)
    coverages: list = field(default_factory=list)


@dataclass
class ModelSpec:
    """Complete specification of an Epigrass project."""

    name: str
    model_type: str  # e.g. SIR, SEIR_cont, Custom
    sites: list = field(default_factory=list)  # list[Site]
    edges: list = field(default_factory=list)  # list[Edge]
    # Parameter values as raw expression strings (evaluated by Epigrass):
    params: dict = field(default_factory=lambda: {
        "beta": "0.4", "alpha": "1", "e": "0.2", "r": "0.14",
        "delta": "0", "B": "0", "w": "0", "p": "0",
    })
    # Initial conditions as raw expression strings; keys are S, E, I:
    inits: dict = field(default_factory=lambda: {"S": "N", "E": "0", "I": "0"})
    seed: list = field(default_factory=list)  # list[SeedEvent]
    vaccinate: list = field(default_factory=list)  # list[VaccinationEvent]
    shapefile: tuple = ("map.gpkg", "name", "geocode")  # (file, name field, geocode field)
    encoding: str = "utf-8"
    do_transp: bool = True
    stochastic: bool = False
    speed: float = 0.0
    steps: int = 365
    sqlout: bool = True
    report: int = 0
    site_rep: list = field(default_factory=list)
    replicas: int = 0
    rand_seed: bool = False
    batch: list = field(default_factory=list)


def validate_spec(spec: ModelSpec) -> list:
    """Return a list of problems found in *spec* (empty list means valid)."""
    errors = []
    if not spec.name:
        errors.append("Model name is empty.")
    if not spec.sites:
        errors.append("The model has no sites.")
    geocodes = set()
    names = set()
    for s in spec.sites:
        if s.geocode in geocodes:
            errors.append(f"Duplicated geocode {s.geocode} (site '{s.name}').")
        geocodes.add(s.geocode)
        if s.name in names:
            errors.append(f"Duplicated site name '{s.name}'.")
        names.add(s.name)
        if s.population <= 0:
            errors.append(f"Site '{s.name}' has non-positive population ({s.population}).")
        if not (-90.0 <= s.lat <= 90.0 and -180.0 <= s.lon <= 180.0):
            errors.append(f"Site '{s.name}' has invalid coordinates ({s.lat}, {s.lon}).")
    known = {s.geocode for s in spec.sites}
    for e in spec.edges:
        if e.source not in known:
            errors.append(f"Edge source geocode {e.source} is not a site.")
        if e.dest not in known:
            errors.append(f"Edge destination geocode {e.dest} is not a site.")
    for seed in spec.seed:
        if seed.geocode not in known:
            errors.append(f"Seed geocode {seed.geocode} is not a site.")
    if not spec.inits:
        errors.append("No initial conditions defined.")
    return errors


def _py(obj) -> str:
    """Render *obj* as a Python literal suitable for eval() inside the .epg file."""
    return repr(obj)


def render_epg(spec: ModelSpec) -> str:
    """Render the ``model.epg`` script for *spec*."""
    seed = [(int(s.geocode), str(s.state), int(s.amount)) for s in spec.seed]
    vaccinate = [
        (v.geocode, list(v.times), [float(c) for c in v.coverages])
        for v in spec.vaccinate
    ]
    inits = "\n".join(f"{k} = {spec.inits[k]}" for k in ("S", "E", "I") if k in spec.inits)
    fmt = dict(
        shapefile=_py(list(spec.shapefile)),
        encoding=spec.encoding,
        modtype=spec.model_type,
        beta=spec.params.get("beta", "0.4"),
        alpha=spec.params.get("alpha", "1"),
        e=spec.params.get("e", "0"),
        r=spec.params.get("r", "0.14"),
        delta=spec.params.get("delta", "0"),
        B=spec.params.get("B", "0"),
        w=spec.params.get("w", "0"),
        p=spec.params.get("p", "0"),
        inits=inits,
        seed=_py(seed),
        vaccinate=_py(vaccinate),
        quarantine=_py([]),
        do_transp=int(bool(spec.do_transp)),
        stochastic=int(bool(spec.stochastic)),
        speed=repr(float(spec.speed)),
        steps=int(spec.steps),
        sqlout=int(bool(spec.sqlout)),
        report=int(spec.report),
        site_rep=_py([int(g) for g in spec.site_rep]),
        replicas=int(spec.replicas),
        rand_seed=int(bool(spec.rand_seed)),
        batch=_py(list(spec.batch)),
    )
    return _EPG_TEMPLATE.format(**fmt)


def sites_csv_text(spec: ModelSpec) -> str:
    """Render ``sites.csv`` content. Columns are positional (see module docstring)."""
    import io

    out = io.StringIO()
    n_values = max((len(s.values) for s in spec.sites), default=0)
    header = SITES_HEADER + [f"value{i + 1}" for i in range(n_values)]
    writer = csv.writer(out, lineterminator="\n")
    writer.writerow(header)
    for s in spec.sites:
        writer.writerow(
            [f"{s.lat:.6f}", f"{s.lon:.6f}", s.name, f"{s.population:g}", s.geocode,
             *s.values]
        )
    return out.getvalue()


def edges_csv_text(spec: ModelSpec) -> str:
    """Render ``edges.csv`` content. Columns are positional (see module docstring)."""
    import io

    names = {s.geocode: str(s.name) for s in spec.sites}
    out = io.StringIO()
    writer = csv.writer(out, lineterminator="\n")
    writer.writerow(EDGES_HEADER)
    for e in spec.edges:
        writer.writerow(
            [
                names.get(e.source, e.source),
                names.get(e.dest, e.dest),
                f"{float(e.flow_sd):g}",
                f"{float(e.flow_ds):g}",
                f"{float(e.distance_km):g}",
                e.source,
                e.dest,
            ]
        )
    return out.getvalue()


def spec_to_dict(spec: ModelSpec) -> dict:
    """JSON-serialisable representation of *spec* (for model_spec.json)."""
    return {
        "name": spec.name,
        "model_type": spec.model_type,
        "steps": spec.steps,
        "params": dict(spec.params),
        "inits": dict(spec.inits),
        "transport": {
            "enabled": bool(spec.do_transp),
            "stochastic": bool(spec.stochastic),
            "speed": float(spec.speed),
        },
        "seed": [s.__dict__ for s in spec.seed],
        "vaccinate": [v.__dict__ for v in spec.vaccinate],
        "shapefile": list(spec.shapefile),
        "sites": [
            {
                "name": s.name, "population": s.population, "geocode": s.geocode,
                "lat": s.lat, "lon": s.lon, "values": list(s.values),
            }
            for s in spec.sites
        ],
        "edges": [e.__dict__ for e in spec.edges],
    }


def write_project(spec: ModelSpec, folder) -> dict:
    """Write the full model project into *folder*.

    Returns a dict with the paths of the generated files.  Raises ValueError if
    the spec does not validate.
    """
    errors = validate_spec(spec)
    if errors:
        raise ValueError("Invalid model specification:\n- " + "\n- ".join(errors))

    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    paths = {}
    (paths["epg"], paths["sites"], paths["edges"], paths["json"]) = (
        folder / "model.epg",
        folder / "sites.csv",
        folder / "edges.csv",
        folder / "model_spec.json",
    )
    paths["epg"].write_text(render_epg(spec), encoding="utf-8")
    paths["sites"].write_text(sites_csv_text(spec), encoding="utf-8")
    paths["edges"].write_text(edges_csv_text(spec), encoding="utf-8")
    paths["json"].write_text(
        json.dumps(spec_to_dict(spec), indent=2, ensure_ascii=False), encoding="utf-8"
    )
    log.info("Epigrass project written to %s", folder)
    return {k: str(v) for k, v in paths.items()}
